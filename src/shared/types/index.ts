/**
 * Shared type definitions used across main, preload, and renderer.
 *
 * These mirror the database schema but are intentionally plain (no Drizzle types)
 * so the renderer can import them without bundling Drizzle.
 */

export type Currency = 'USD' | 'LBP';
export type SellingUnit = 'WEIGHT' | 'PACKAGE' | 'PIECE';
export type Language = 'en' | 'ar';
export type SaleStatus = 'COMPLETED' | 'SUSPENDED' | 'VOIDED' | 'RETURNED';
export type PaymentType = 'USD' | 'LBP' | 'MIXED' | 'CREDIT';
export type MovementType =
  | 'SALE'
  | 'ADD_STOCK'
  | 'WASTE'
  | 'RETURN'
  | 'ADJUSTMENT';
export type ReturnType = 'FULL' | 'PARTIAL';
export type CustomerTxnType = 'CREDIT' | 'PAYMENT' | 'ADJUSTMENT';
export type ExpenseCategory =
  | 'ELECTRICITY'
  | 'WATER'
  | 'RENT'
  | 'TRANSPORT'
  | 'MAINTENANCE'
  | 'OTHER';
export type ExpensePaymentSource = 'CASH' | 'OWNER';


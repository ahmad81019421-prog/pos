/**
 * KPI definitions (single source of truth; PRD 32, 40, 41). All "USD-equivalent"
 * values use the exchange rate recorded on the original transaction.
 *
 *   gross sales    = completed + later-returned invoices created in the range
 *   returns        = refunds issued in the range (revenue reversed at the sale's rate)
 *   net sales      = gross sales - returns
 *   cost of goods  = cost of items sold - cost of items returned (sale-time snapshots)
 *   gross profit   = net sales - cost of goods
 *   expenses       = expenses dated in the range
 *   waste          = cost of wasted stock recorded in the range (cost at time of waste)
 *   net profit     = gross profit - expenses - waste
 */
export interface SalesReport {
  totalUsdCents: number;
  totalLbp: number;
  /** Gross sales (before returns), USD-equivalent. */
  totalUsdEquivalentCents: number;
  /** Refunds issued in the range, USD-equivalent. */
  returnsUsdCents: number;
  netSalesUsdEquivalentCents: number;
  /** Cost of goods sold, net of returned goods. */
  costUsdCents: number;
  grossProfitUsdCents: number;
  expensesUsdCents: number;
  expensesCashUsdCents: number;
  expensesOwnerUsdCents: number;
  expensesUnclassifiedUsdCents: number;
  wasteUsdCents: number;
  netProfitUsdCents: number;
  invoiceCount: number;
}

